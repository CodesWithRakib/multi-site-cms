import type { Metadata } from 'next';
import Link from 'next/link';
import { AlertTriangle, ArrowLeft, Calendar, Clock, Eye, ShieldAlert } from 'lucide-react';
import { DocRenderer } from '@/components/content/DocRenderer';
import { fetchDraftPreview } from '@/lib/api';

export const metadata: Metadata = {
  title: 'Draft Preview',
  robots: {
    index: false,
    follow: false,
  },
};

interface PreviewPageProps {
  params: Promise<{ postId: string }>;
  searchParams: Promise<{ token?: string }>;
}

export default async function DraftPreviewPage({ params, searchParams }: PreviewPageProps) {
  const { postId } = await params;
  const { token } = await searchParams;

  if (!token) {
    return (
      <div className="mx-auto max-w-xl px-4 py-20 text-center space-y-4">
        <ShieldAlert className="h-12 w-12 text-amber-600 mx-auto" />
        <h1 className="font-serif text-2xl font-bold text-foreground">Preview Token Required</h1>
        <p className="text-sm text-muted-foreground">
          Draft previews require a signed authorization token generated by the CMS dashboard.
        </p>
        <Link
          href="/"
          className="inline-flex items-center gap-1.5 text-sm font-semibold text-primary hover:underline"
        >
          <ArrowLeft className="h-4 w-4" /> Return to Front Page
        </Link>
      </div>
    );
  }

  const article = await fetchDraftPreview(postId, token);

  if (!article) {
    return (
      <div className="mx-auto max-w-xl px-4 py-20 text-center space-y-4">
        <AlertTriangle className="h-12 w-12 text-rose-600 mx-auto" />
        <h1 className="font-serif text-2xl font-bold text-foreground">
          Preview Link Expired or Invalid
        </h1>
        <p className="text-sm text-muted-foreground">
          This preview link is no longer valid. Return to the CMS editor and click
          &ldquo;Preview&rdquo; to generate a fresh link.
        </p>
        <Link
          href="/"
          className="inline-flex items-center gap-1.5 text-sm font-semibold text-primary hover:underline"
        >
          <ArrowLeft className="h-4 w-4" /> Return to Front Page
        </Link>
      </div>
    );
  }

  return (
    <div>
      {/* Floating Preview Banner */}
      <div className="sticky top-16 z-30 flex items-center justify-between bg-amber-500 text-amber-950 px-4 py-2 text-xs font-semibold shadow-md">
        <div className="flex items-center gap-2">
          <Eye className="h-4 w-4 animate-pulse" />
          <span>PREVIEW MODE — Viewing unpublished draft content. Do not share publicly.</span>
        </div>
        <span className="font-mono text-[11px] bg-amber-600/30 px-2 py-0.5 rounded">
          Post: {postId.slice(0, 8)}
        </span>
      </div>

      <article className="mx-auto max-w-4xl px-4 sm:px-6 py-8 sm:py-12 space-y-10">
        <header className="space-y-4">
          <span className="inline-flex items-center rounded-full bg-amber-500/10 px-3 py-1 text-xs font-semibold uppercase tracking-wider text-amber-700 dark:text-amber-400">
            Unpublished Draft
          </span>

          <h1 className="font-serif text-3xl sm:text-5xl font-extrabold tracking-tight text-foreground">
            {article.title}
          </h1>

          {article.excerpt && (
            <p className="font-serif text-lg text-muted-foreground leading-relaxed">
              {article.excerpt}
            </p>
          )}

          <div className="flex items-center gap-4 border-y border-border py-3 text-xs text-muted-foreground">
            <span className="inline-flex items-center gap-1">
              <Calendar className="h-3.5 w-3.5" /> Draft Snapshot
            </span>
            <span className="inline-flex items-center gap-1">
              <Clock className="h-3.5 w-3.5" /> ~{article.readingTimeMinutes} min read
            </span>
          </div>
        </header>

        <div className="pt-2">
          <DocRenderer document={article.body} />
        </div>
      </article>
    </div>
  );
}
